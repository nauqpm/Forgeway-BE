import { SPACE_ROLES, SpaceRole } from './space-role.constants';
import { PERMISSIONS } from '../../modules/authorization/authorization.constants';

export const WORKSPACE_PERMISSIONS = {
  WORKSPACE_UPDATE: PERMISSIONS.WORKSPACE_UPDATE,
  WORKSPACE_DELETE: PERMISSIONS.WORKSPACE_DELETE,
  TASK_VIEW: PERMISSIONS.TASK_VIEW,
  TASK_CREATE: PERMISSIONS.TASK_CREATE,
  TASK_EDIT: PERMISSIONS.TASK_EDIT,
  TASK_DELETE: PERMISSIONS.TASK_DELETE,
  TASK_MOVE: PERMISSIONS.TASK_MOVE,
  TASK_BULK_IMPORT: PERMISSIONS.TASK_BULK_IMPORT,
  SPRINT_MANAGE: PERMISSIONS.SPRINT_MANAGE,
  PAGE_VIEW: PERMISSIONS.PAGE_VIEW,
  PAGE_CREATE: PERMISSIONS.PAGE_CREATE,
  PAGE_EDIT: PERMISSIONS.PAGE_EDIT,
  PAGE_DELETE: PERMISSIONS.PAGE_DELETE,
} as const;

export type WorkspacePermission =
  (typeof WORKSPACE_PERMISSIONS)[keyof typeof WORKSPACE_PERMISSIONS];

export const WORKSPACE_ROLE_PERMISSIONS: Record<
  SpaceRole,
  WorkspacePermission[]
> = {
  [SPACE_ROLES.WORKSPACE_ADMIN]: Object.values(WORKSPACE_PERMISSIONS),
  [SPACE_ROLES.MEMBER]: [
    WORKSPACE_PERMISSIONS.TASK_VIEW,
    WORKSPACE_PERMISSIONS.TASK_CREATE,
    WORKSPACE_PERMISSIONS.TASK_EDIT,
    WORKSPACE_PERMISSIONS.TASK_DELETE,
    WORKSPACE_PERMISSIONS.TASK_MOVE,
    WORKSPACE_PERMISSIONS.SPRINT_MANAGE,
    WORKSPACE_PERMISSIONS.PAGE_VIEW,
    WORKSPACE_PERMISSIONS.PAGE_CREATE,
    WORKSPACE_PERMISSIONS.PAGE_EDIT,
    WORKSPACE_PERMISSIONS.PAGE_DELETE,
  ],
  [SPACE_ROLES.VIEWER]: [
    WORKSPACE_PERMISSIONS.TASK_VIEW,
    WORKSPACE_PERMISSIONS.PAGE_VIEW,
  ],
};

export const getPermissionsForWorkspaceRole = (
  role?: string,
): WorkspacePermission[] => {
  if (!role || !(role in WORKSPACE_ROLE_PERMISSIONS)) {
    return [];
  }

  return WORKSPACE_ROLE_PERMISSIONS[role as SpaceRole];
};
